#!/usr/bin/env python3
"""R1 oracle inputs: write QE 7.6 pw.x scf and nscf inputs that match a BAANDI
`baandi nscf` run (nscf.json): same cell, atoms, UPF file names, cutoff, FFT
grid, k list (explicit crystal coordinates, no symmetry or inversion
reduction) and band count, with diago_full_acc. Reads only nscf.json; never
reads pseudopotential contents. Python 3.9+, standard library only.

  python3 -I make_qe_r1.py OUT/nscf.json --nr 25 25 25 --scf-kgrid 4 4 4 --prefix si2_444 --dir qe
"""
import argparse
import json
from pathlib import Path


def fmt(x):
    return repr(float(x))


def common(meta, nr, prefix, calculation, nbnd):
    lattice = meta["lattice_columns_bohr"]  # columns are lattice vectors
    rows = [[lattice[i][j] for i in range(3)] for j in range(3)]
    species = sorted({a["species"] for a in meta["atoms"]})
    upf = {p["species"]: Path(p["path"]).name for p in meta["pseudopotentials"]}
    ecut_ry = 2.0 * meta["cutoff_hartree"]
    lines = [
        "! Generated by tests/reference/response/r1/make_qe_r1.py from BAANDI nscf.json",
        "! input_sha256 " + meta["input_sha256"] + "; UPF sha256 "
        + ", ".join(p["species"] + "=" + p["sha256"] for p in meta["pseudopotentials"]),
        "&CONTROL",
        f"  calculation = '{calculation}',",
        f"  prefix = '{prefix}',",
        "  pseudo_dir = '.',",
        "  outdir = './qe-work',",
        "  verbosity = 'high',",
        "/",
        "&SYSTEM",
        "  ibrav = 0,",
        f"  nat = {len(meta['atoms'])},",
        f"  ntyp = {len(species)},",
        f"  ecutwfc = {fmt(ecut_ry)},",
        f"  ecutrho = {fmt(4.0 * ecut_ry)},",
        f"  nbnd = {nbnd},",
        "  occupations = 'fixed',",
        "  nosym = .true.,",
        "  noinv = .true.,",
        f"  nr1 = {nr[0]},",
        f"  nr2 = {nr[1]},",
        f"  nr3 = {nr[2]},",
        "/",
        "&ELECTRONS",
        "  diagonalization = 'david',",
        "  diago_full_acc = .true.,",
        "  conv_thr = 1.0d-12,",
        "  mixing_beta = 0.7,",
        "  electron_maxstep = 200,",
        "/",
        "ATOMIC_SPECIES",
    ]
    lines += [f"{s} 1.0 {upf[s]}" for s in species]
    lines.append("CELL_PARAMETERS bohr")
    lines += [" ".join(fmt(x) for x in r) for r in rows]
    lines.append("ATOMIC_POSITIONS crystal")
    lines += [a["species"] + " " + " ".join(fmt(x) for x in a["fractional"]) for a in meta["atoms"]]
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("nscf_json")
    ap.add_argument("--nr", nargs=3, type=int, required=True, help="BAANDI FFT grid (baandi grid)")
    ap.add_argument("--scf-kgrid", nargs=3, type=int, required=True)
    ap.add_argument("--prefix", required=True)
    ap.add_argument("--dir", default=".")
    a = ap.parse_args()
    meta = json.loads(Path(a.nscf_json).read_text())
    out = Path(a.dir)
    out.mkdir(parents=True, exist_ok=True)
    occupied = max(meta["occupied_bands"])
    scf = common(meta, a.nr, a.prefix, "scf", occupied + 4)
    scf += ["K_POINTS automatic", " ".join(str(n) for n in a.scf_kgrid) + " 0 0 0"]
    nscf = common(meta, a.nr, a.prefix, "nscf", meta["nbands"])
    points = meta["kpoints"]
    nscf += ["K_POINTS crystal", str(len(points))]
    nscf += [" ".join(fmt(x) for x in p["fractional"]) + " " + fmt(p["weight"]) for p in points]
    (out / f"{a.prefix}-scf.in").write_text("\n".join(scf) + "\n")
    (out / f"{a.prefix}-nscf.in").write_text("\n".join(nscf) + "\n")
    print(f"wrote {out}/{a.prefix}-scf.in and {a.prefix}-nscf.in ({len(points)} k, nbnd {meta['nbands']})")


if __name__ == "__main__":
    main()
