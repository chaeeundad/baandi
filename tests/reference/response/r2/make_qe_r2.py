#!/usr/bin/env python3
"""R2 oracle: QE 7.6 pw.x scf + nscf inputs matching a BAANDI `baandi dielectric` input (protocol tests/reference/response/r2/README.md):
same cell, atoms, UPF file names, ecutwfc (ecutrho = 4 ecutwfc), FFT grid (--nr from `baandi grid`), SCF on the Gamma-centred kgrid, NSCF on the
FULL Gamma-centred response mesh (explicit crystal k list, nosym, noinv), nbnd = bands + extra (top bands are not used by Yambo), fixed occupations,
diago_full_acc, conv_thr 1e-12. Reads the TOML only (Python 3.11 tomllib), never UPF contents.
Written by the dev08 session on 2026-11-27 (MIT, no QE/Yambo source).
usage: make_qe_r2.py input.toml --nr N1 N2 N3 --prefix P [--extra-bands 8] [--dir .]"""
import argparse, tomllib
from pathlib import Path

ap = argparse.ArgumentParser(); ap.add_argument("toml"); ap.add_argument("--nr", nargs=3, type=int, required=True)
ap.add_argument("--prefix", required=True); ap.add_argument("--extra-bands", type=int, default=8); ap.add_argument("--dir", default=".")
a = ap.parse_args(); t = tomllib.loads(Path(a.toml).read_text())
sy, bs, rs = t["system"], t["basis"], t["response"]
assert sy.get("lattice_unit") == "bohr"
lat = sy["lattice_vectors"]; atoms = sy["atoms"]; pp = t["pseudopotentials"]; species = sorted(pp)
fn = t["xc"]["functional"]; dft = {"lda-pz": "PZ", "pbe": "PBE"}[fn]
nb = rs["bands"] + a.extra_bands; km = rs.get("k_mesh", bs["kgrid"]); kg = bs["kgrid"]
def common(calc, nbnd):
    L = [f"! Generated by make_qe_r2.py from {Path(a.toml).name} (R2 oracle protocol)", "&CONTROL", f"  calculation = '{calc}',", f"  prefix = '{a.prefix}',",
         "  pseudo_dir = '.',", "  outdir = './qe-work',", "  verbosity = 'high',", "/", "&SYSTEM", "  ibrav = 0,", f"  nat = {len(atoms)},", f"  ntyp = {len(species)},",
         f"  ecutwfc = {float(bs['ecutwfc_ry'])!r},", f"  ecutrho = {4.0 * float(bs['ecutwfc_ry'])!r},", f"  input_dft = '{dft}',", "  occupations = 'fixed',",
         f"  nr1 = {a.nr[0]},", f"  nr2 = {a.nr[1]},", f"  nr3 = {a.nr[2]},"]
    if nbnd: L += [f"  nbnd = {nbnd},", "  nosym = .true.,", "  noinv = .true.,"]
    L += ["/", "&ELECTRONS", "  diagonalization = 'david',", "  diago_full_acc = .true.,", "  conv_thr = 1.0d-12,", "  mixing_beta = 0.7,", "  electron_maxstep = 200,", "/",
          "ATOMIC_SPECIES"] + [f"{s} 1.0 {pp[s]}" for s in species]
    L += ["CELL_PARAMETERS bohr"] + [" ".join(repr(float(x)) for x in v) for v in lat]
    L += ["ATOMIC_POSITIONS crystal"] + [f"{x['species']} " + " ".join(repr(float(c)) for c in x["fractional"]) for x in atoms]
    return L
out = Path(a.dir); out.mkdir(parents=True, exist_ok=True)
scf = common("scf", 0) + ["K_POINTS automatic", f"{kg[0]} {kg[1]} {kg[2]} 0 0 0"]
pts = [(i / km[0], j / km[1], k / km[2]) for i in range(km[0]) for j in range(km[1]) for k in range(km[2])]
nscf = common("nscf", nb) + ["K_POINTS crystal", str(len(pts))] + [f"{x!r} {y!r} {z!r} 1.0" for x, y, z in pts]
(out / f"{a.prefix}-scf.in").write_text("\n".join(scf) + "\n"); (out / f"{a.prefix}-nscf.in").write_text("\n".join(nscf) + "\n")
print(f"wrote {a.prefix}-scf.in / {a.prefix}-nscf.in: {len(pts)} k (full Gamma-centred {km}), nbnd {nb} = {rs['bands']} + {a.extra_bands}, nr {a.nr}, {dft}")
