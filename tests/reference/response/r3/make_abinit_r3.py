#!/usr/bin/env python3
"""R3 oracle input: write an ABINIT input (multi-dataset .abi) matching a
BAANDI `baandi rpa` run (rpa.json): same cell, atoms, pseudopotential file
names, wavefunction cutoff, FFT grid, Gamma-centred k mesh, band count and
response cutoff per point of the series, imaginary-frequency count, RPA
correlation energy by `gwrpacorr` in the screening driver (optdriver 3).
Reads only rpa.json; never reads pseudopotential contents. Python 3.9+,
standard library only. Variable names follow the public ABINIT
documentation (https://docs.abinit.org/variables/); every value must be
checked against the documentation of the ABINIT version actually built on
dev08 (README.md) before the run is recorded.

  python3 -I make_abinit_r3.py OUT/rpa.json --nfreqim 16 --buffer 8 --out si2_444.abi
"""
import argparse
import json
from pathlib import Path

# Atomic numbers (znucl) of the elements used by the R2/R3 sets and neighbours.
Z = {
    "H": 1, "He": 2, "Li": 3, "Be": 4, "B": 5, "C": 6, "N": 7, "O": 8, "F": 9,
    "Ne": 10, "Na": 11, "Mg": 12, "Al": 13, "Si": 14, "P": 15, "S": 16,
    "Cl": 17, "Ar": 18, "K": 19, "Ca": 20, "Ga": 31, "Ge": 32, "As": 33,
    "Kr": 36,
}


def element(label):
    letters = "".join(c for c in label if c.isalpha())
    for n in (2, 1):
        if letters[:n] in Z:
            return letters[:n]
    raise SystemExit(f"unknown element for species label {label!r}; extend Z")


def fmt(x):
    return repr(float(x))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rpa_json")
    ap.add_argument("--nfreqim", type=int, default=None,
                    help="imaginary frequencies (default: BAANDI frequency_points)")
    ap.add_argument("--buffer", type=int, default=8,
                    help="NSCF buffer bands (nbdbuf) above the largest band count")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    m = json.loads(Path(a.rpa_json).read_text())
    if m.get("kind") != "baandi_rpa_r3":
        raise SystemExit("not a baandi rpa.json")
    s = m["settings"]
    cols = m["lattice_columns_bohr"]  # columns are lattice vectors
    rows = [[cols[i][j] for i in range(3)] for j in range(3)]
    species = []
    for at in m["structure"]:
        if at["species"] not in species:
            species.append(at["species"])
    upf = {p["species"]: Path(p["path"]).name for p in m["pseudopotentials"]}
    cutoffs = s["ecut_chi_series_hartree"]
    bands = s["bands_per_cutoff"]
    nfreq = a.nfreqim or s["frequency_points"]
    nb_max = max(bands)
    ncut = len(cutoffs)
    lines = [
        "# Generated by tests/reference/response/r3/make_abinit_r3.py from BAANDI rpa.json",
        "# input_sha256 " + m["input_sha256"] + "; pseudopotential sha256 "
        + ", ".join(p["species"] + "=" + p["sha256"] for p in m["pseudopotentials"]),
        "# BAANDI E_c (Ha/cell) per cutoff: " + " ".join(fmt(e) for e in m["e_c_hartree_per_cell"]),
        "# Dataset 1: SCF; 2: NSCF with many bands; 3..: screening + RPA correlation, one per cutoff",
        f"ndtset {2 + ncut}",
        "acell 3*1.0",
        "rprim",
    ]
    lines += ["  " + " ".join(fmt(x) for x in r) for r in rows]
    lines += [
        f"natom {len(m['structure'])}",
        f"ntypat {len(species)}",
        "znucl " + " ".join(str(Z[element(sp)]) for sp in species),
        "typat " + " ".join(str(species.index(at["species"]) + 1) for at in m["structure"]),
        "xred",
    ]
    lines += ["  " + " ".join(fmt(x) for x in at["fractional"]) for at in m["structure"]]
    lines += [
        'pseudos "' + ", ".join(upf[sp] for sp in species) + '"',
        "# functional from the pseudopotential files (BAANDI: " + m["functional"] + ");",
        "# confirm the ixc printed in the ABINIT log matches",
        f"ecut {fmt(m['cutoff_hartree'])}",
        "ngfft " + " ".join(str(n) for n in s["fft_grid"]),
        "occopt 1",
        "kptopt 1",
        "ngkpt " + " ".join(str(n) for n in s["k_mesh"]),
        "nshiftk 1",
        "shiftk 0 0 0",
        "istwfk *1",
        "",
        "# 1: ground state",
        "tolvrs1 1.0d-14",
        "nstep1 200",
        "",
        "# 2: NSCF bands (all bands up to the largest BAANDI count + buffer)",
        "iscf2 -2",
        "getden2 1",
        f"nband2 {nb_max + a.buffer}",
        f"nbdbuf2 {a.buffer}",
        "tolwfr2 1.0d-18",
        "nstep2 400",
        "",
        "# 3..: screening (optdriver 3) with the RPA correlation energy (gwrpacorr 1:",
        "# exact coupling-constant integration), imaginary frequencies only;",
        "# response sphere ecuteps = BAANDI ecut_chi, nband = BAANDI bands of that cutoff;",
        "# inclvkb 2: nonlocal commutator in the q -> 0 dipoles (as BAANDI).",
    ]
    for i, (c, nb) in enumerate(zip(cutoffs, bands)):
        d = 3 + i
        lines += [
            f"optdriver{d} 3",
            f"getwfk{d} 2",
            f"nband{d} {nb}",
            f"ecuteps{d} {fmt(c)}",
            f"ecutwfn{d} {fmt(m['cutoff_hartree'])}",
            # gwrpacorr and nfreqim require gwcalctyp in [1,11,21] (Gauss-Legendre
            # imaginary-axis mesh); nfreqre only applies to real-axis contour
            # deformation, so it is not set (dev08 check against the ABINIT 10.8.3
            # variable database, 2026-11-27).
            f"gwcalctyp{d} 1",
            f"gwrpacorr{d} 1",
            f"nfreqim{d} {nfreq}",
            f"inclvkb{d} 2",
            "",
        ]
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {a.out}: {ncut} screening datasets, nband up to {nb_max}, nfreqim {nfreq}")


if __name__ == "__main__":
    main()
